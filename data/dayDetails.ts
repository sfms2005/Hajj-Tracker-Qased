export const dayDetails: StageDetails[] = rawDayDetails.map((d) => ({
  ...d,
  duas: [...d.duas, ...commonDuas],
}));

export function getStageDetails(id: number): StageDetails | undefined {
  return dayDetails.find((d) => d.id === id);
}

export function getRulingBadgeClass(ruling: string): string {
  if (ruling.includes("ركن")) {
    return "bg-[#1f3d2b] text-white";
  }
  if (ruling.includes("واجب")) {
    return "bg-amber-100 text-amber-950 border border-amber-300/60";
  }
  if (ruling === "سنة" || ruling.includes("مستحب")) {
    return "bg-sky-100 text-sky-950 border border-sky-200/80";
  }
  if (ruling === "مباح") {
    return "bg-neutral-100 text-neutral-700 border border-neutral-200";
  }
  return "bg-[var(--color-bg-soft)] text-[#1f3d2b] border border-[var(--color-track)]";
}
